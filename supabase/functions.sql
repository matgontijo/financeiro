-- Permite restaurar backups preservando os IDs originais
alter table accounts     alter column id set generated by default;
alter table categories   alter column id set generated by default;
alter table transactions alter column id set generated by default;
alter table budgets      alter column id set generated by default;
alter table recurring    alter column id set generated by default;
alter table goals        alter column id set generated by default;

-- Depois de uma restauração, realinha os contadores de ID
create or replace function fix_sequences() returns void language sql as $$
  select setval(pg_get_serial_sequence('accounts', 'id'),     coalesce(max(id), 0) + 1, false) from accounts;
  select setval(pg_get_serial_sequence('categories', 'id'),   coalesce(max(id), 0) + 1, false) from categories;
  select setval(pg_get_serial_sequence('transactions', 'id'), coalesce(max(id), 0) + 1, false) from transactions;
  select setval(pg_get_serial_sequence('budgets', 'id'),      coalesce(max(id), 0) + 1, false) from budgets;
  select setval(pg_get_serial_sequence('recurring', 'id'),    coalesce(max(id), 0) + 1, false) from recurring;
  select setval(pg_get_serial_sequence('goals', 'id'),        coalesce(max(id), 0) + 1, false) from goals;
$$;

-- Saldo real e saldo conferido de cada conta (só lançamentos PAGOS contam;
-- transferência recebida confere pelo lado reconciled_in)
create or replace function accounts_with_balances()
returns table (
  id bigint, name text, type text, initial_balance bigint, color text,
  archived smallint, closing_day int, due_day int,
  balance bigint, reconciled_balance bigint
) language sql stable as $$
  select a.id, a.name, a.type, a.initial_balance, a.color,
         a.archived, a.closing_day, a.due_day,
    a.initial_balance
      + coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'receita' and t.status = 'pago'), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'despesa' and t.status = 'pago'), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'transferencia' and t.status = 'pago'), 0)
      + coalesce((select sum(t.amount) from transactions t where t.to_account_id = a.id and t.type = 'transferencia' and t.status = 'pago'), 0)
      as balance,
    a.initial_balance
      + coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'receita' and t.status = 'pago' and t.reconciled = 1), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'despesa' and t.status = 'pago' and t.reconciled = 1), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'transferencia' and t.status = 'pago' and t.reconciled = 1), 0)
      + coalesce((select sum(t.amount) from transactions t where t.to_account_id = a.id and t.type = 'transferencia' and t.status = 'pago' and t.reconciled_in = 1), 0)
      as reconciled_balance
  from accounts a
  order by a.archived, a.name
$$;

-- Totais de um mês (AAAA-MM)
create or replace function month_totals(m text)
returns table (receitas bigint, despesas bigint, receitas_pendentes bigint, despesas_pendentes bigint)
language sql stable as $$
  select
    coalesce(sum(case when type = 'receita' then amount end), 0),
    coalesce(sum(case when type = 'despesa' then amount end), 0),
    coalesce(sum(case when status = 'pendente' and type = 'receita' then amount end), 0),
    coalesce(sum(case when status = 'pendente' and type = 'despesa' then amount end), 0)
  from transactions
  where to_char(date, 'YYYY-MM') = m
$$;

-- Totais por categoria num período (receitas e despesas)
create or replace function category_range_totals(dfrom date, dto date)
returns table (id bigint, name text, kind text, color text, icon text, total bigint, count bigint)
language sql stable as $$
  select c.id, c.name, c.kind, c.color, c.icon, sum(t.amount)::bigint, count(*)::bigint
  from transactions t join categories c on c.id = t.category_id
  where t.date >= dfrom and t.date <= dto and t.type in ('receita', 'despesa')
  group by c.id, c.name, c.kind, c.color, c.icon
  order by 6 desc
$$;

-- Orçamentos com o gasto do mês
create or replace function budgets_with_spent(m text)
returns table (id bigint, category_id bigint, amount bigint, name text, color text, icon text, spent bigint)
language sql stable as $$
  select b.id, b.category_id, b.amount, c.name, c.color, c.icon,
    coalesce((select sum(t.amount) from transactions t
      where t.category_id = b.category_id and t.type = 'despesa'
        and to_char(t.date, 'YYYY-MM') = m), 0)::bigint
  from budgets b join categories c on c.id = b.category_id
  order by c.name
$$;

-- Série mensal (n meses terminando em end_month AAAA-MM)
create or replace function monthly_series(n int, end_month text)
returns table (month text, receitas bigint, despesas bigint)
language sql stable as $$
  with months as (
    select to_char((end_month || '-01')::date - (i || ' months')::interval, 'YYYY-MM') as m
    from generate_series(n - 1, 0, -1) as i
  )
  select months.m,
    coalesce(sum(case when t.type = 'receita' then t.amount end), 0)::bigint,
    coalesce(sum(case when t.type = 'despesa' then t.amount end), 0)::bigint
  from months left join transactions t on to_char(t.date, 'YYYY-MM') = months.m
  group by months.m order by months.m
$$;

-- Patrimônio (saldo total pago) no fim de cada um dos últimos n meses
create or replace function networth_series(n int)
returns table (month text, total bigint)
language sql stable as $$
  with months as (
    select to_char(date_trunc('month', now()) - (i || ' months')::interval, 'YYYY-MM') as m,
           (date_trunc('month', now()) - (i || ' months')::interval + interval '1 month' - interval '1 day')::date as month_end
    from generate_series(n - 1, 0, -1) as i
  )
  select months.m,
    (select coalesce(sum(
      a.initial_balance
      + coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'receita' and t.status = 'pago' and t.date <= months.month_end), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'despesa' and t.status = 'pago' and t.date <= months.month_end), 0)
      - coalesce((select sum(t.amount) from transactions t where t.account_id = a.id and t.type = 'transferencia' and t.status = 'pago' and t.date <= months.month_end), 0)
      + coalesce((select sum(t.amount) from transactions t where t.to_account_id = a.id and t.type = 'transferencia' and t.status = 'pago' and t.date <= months.month_end), 0)
    ), 0) from accounts a where a.archived = 0)::bigint
  from months order by months.m
$$;

-- Matriz anual: total por categoria × mês
create or replace function annual_rows(y text)
returns table (id bigint, name text, kind text, icon text, color text, mm int, total bigint)
language sql stable as $$
  select c.id, c.name, c.kind, c.icon, c.color,
         extract(month from t.date)::int, sum(t.amount)::bigint
  from transactions t join categories c on c.id = t.category_id
  where to_char(t.date, 'YYYY') = y and t.type in ('receita', 'despesa')
  group by c.id, c.name, c.kind, c.icon, c.color, 6
$$;

-- Sugestões de autocompletar (descrições mais usadas, com última categoria/conta/valor)
create or replace function suggestions_list()
returns table (description text, type text, category_id bigint, account_id bigint, amount bigint, uses bigint, last_used date)
language sql stable as $$
  select distinct on (lower(t.description), t.type)
    t.description, t.type, t.category_id, t.account_id, t.amount,
    count(*) over (partition by lower(t.description), t.type)::bigint as uses,
    max(t.date) over (partition by lower(t.description), t.type) as last_used
  from transactions t
  where t.type in ('receita', 'despesa')
  order by lower(t.description), t.type, t.date desc
$$;
